"""Regenerate docs/DATA_SOURCES.md from the registry, the lock manifest, build
stats and a few raw rows of each source. Run after `fraudvae build`.

    python scripts/make_data_docs.py
"""
from __future__ import annotations

import json
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from fraudvae.data import schema  # noqa: E402
from fraudvae.data.adapters.base import _find, source_dir  # noqa: E402
from fraudvae.data.build import STATS  # noqa: E402
from fraudvae.data.fetch import LOCK  # noqa: E402
from fraudvae.data.registry import ORDER, SOURCES  # noqa: E402
from fraudvae.paths import RAW_DIR, ROOT  # noqa: E402

OUT = ROOT / "docs" / "DATA_SOURCES.md"

# which raw file to excerpt per source and how (text lines or pickle head)
EXCERPT = {
    "fdh": ("simulated-data-raw/data/2018-04-01.pkl", "pickle"),
    "capone": ("DS/transactions.txt", "lines"),
    "tabformer": ("card_transaction.v1.csv", "lines"),
    "ulb": ("creditcard.csv", "lines"),
    "paysim": ("PS_20174392719_1491204439457_log.csv", "lines"),
    "sparkov": ("fraudTrain.csv", "lines"),
    "banksim": ("bs140513_032310.csv", "lines"),
    "ieee": ("train_transaction.csv", "lines"),
    "amlworld": ("HI-Small_Trans.csv", "lines"),
    "baf": ("Base.csv", "lines"),
    "fraudecom": ("Fraud_Data.csv", "lines"),
}


def excerpt(key: str, n=4, width=160) -> str | None:
    rel, kind = EXCERPT[key]
    root = source_dir(RAW_DIR, key)
    p = _find(root, rel) if root.exists() else None
    if p is None and key == "capone":
        z = _find(root, "transactions.zip") if root.exists() else None
        if z and zipfile.is_zipfile(z):
            with zipfile.ZipFile(z) as zf, zf.open("transactions.txt") as f:
                return "\n".join(f.readline().decode()[:width].rstrip() for _ in range(n))
    if p is None:
        return None
    if kind == "pickle":
        from fraudvae.data.adapters.fdh import _read_pickle

        df = _read_pickle(p)
        return df.head(n).to_string(max_colwidth=24)
    with open(p, "r", errors="replace") as f:
        return "\n".join(f.readline()[:width].rstrip() for _ in range(n))


def main():
    stats = json.loads(STATS.read_text()) if STATS.exists() else {"sources": {}}
    lock = json.loads(LOCK.read_text()) if LOCK.exists() else {"sources": {}}
    lines = ["# Data sources", "",
             "Generated by `scripts/make_data_docs.py` from `fraudvae/data/registry.py`, the lock manifest and the last build. "
             "Edit the registry, not this file.", ""]
    total = sum(s["rows"] for s in stats["sources"].values())
    fraud = sum(s["fraud"] for s in stats["sources"].values())
    lines += [f"Built corpus: **{total:,} transactions, {fraud:,} labelled fraud ({fraud / max(total, 1):.3%})** across "
              f"{len(stats['sources'])} of {len(ORDER)} sources.", ""]
    lines += ["| key | name | access | rows | fraud rate | license |", "|---|---|---|---:|---:|---|"]
    for k in ORDER:
        s, st = SOURCES[k], stats["sources"].get(k)
        rows = f"{st['rows']:,}" if st else f"~{s.approx_rows:,} (not built)"
        rate = f"{st['fraud_rate']:.3%}" if st else f"~{s.label_rate_hint:.2%}"
        lines.append(f"| {k} | {s.name} | {s.access} | {rows} | {rate} | {s.license} |")
    lines.append("")
    for k in ORDER:
        s, st = SOURCES[k], stats["sources"].get(k)
        lines += [f"## {k}: {s.name}", "", s.context + ".", "",
                  f"- source: <{s.url}>", f"- citation: {s.citation}", f"- license: {s.license}",
                  "- files: " + ", ".join(f"`{f}`" for f in s.files)]
        if s.kaggle_ref:
            lines.append(f"- kaggle: `{s.kaggle_ref}`")
        if s.notes:
            lines.append(f"- notes: {s.notes}")
        lk = lock.get("sources", {}).get(k)
        if lk:
            for f in lk["files"]:
                lines.append(f"- `{f['path']}`: {f['bytes']:,} bytes, sha256 `{f['sha256']}`")
        if st:
            sp = st["splits"]
            lines += ["", f"Built: {st['rows']:,} rows, {st['fraud']:,} fraud. Splits train/val/test = "
                      f"{sp['train']['rows']:,} / {sp['val']['rows']:,} / {sp['test']['rows']:,} "
                      f"(fraud {sp['train']['fraud']:,} / {sp['val']['fraud']:,} / {sp['test']['fraud']:,}).",
                      "", "Fields this source fills (share of rows observed):", ""]
            cov = st["coverage"]
            filled = [(n, c) for n, c in cov.items() if c > 0.005 and not n.startswith("ulb_v")]
            if any(n.startswith("ulb_v") and c > 0.5 for n, c in cov.items()):
                filled.append(("ulb_v1..v28", 1.0))
            lines.append(", ".join(f"`{n}` {c:.0%}" if c < 0.995 else f"`{n}`" for n, c in filled))
        ex = excerpt(k)
        if ex:
            lines += ["", "Raw excerpt:", "", "```", ex, "```"]
        lines.append("")
    lines += ["## Unified schema", "", f"Schema version {schema.SCHEMA_VERSION}. See `docs/SCHEMA.md` for the full field list and the per-source mapping decisions.", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
